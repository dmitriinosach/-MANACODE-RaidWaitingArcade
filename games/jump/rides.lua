function ns.JumpRideFrame(rd, i)
    if i == 0 or not rd.fx then return rd.art end
    local fx = rd.fx[(i - 1) % #rd.fx + 1]
    if not fx then return rd.art end
    local list = rd.frame or {}
    rd.frame = list
    for k = #list, 1, -1 do list[k] = nil end
    for k = 1, #rd.art do list[k] = rd.art[k] end
    for k = 1, #fx do list[#list + 1] = fx[k] end
    return list
end
function ns.JumpRidePaint(rd, slot, list)
    local col = { rd.body, rd.trim, rd.fire, rd.spark or rd.fire }
    for i = 1, #list do
        local c = col[list[i][5]] or rd.body
        slot[i]:SetTexture(c[1], c[2], c[3], 1)
    end
end
